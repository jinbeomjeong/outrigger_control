def load_params(
    path: str | Path | None = None,
    *,
    level: AugerLevel | str | None = None,
    overrides: Mapping[str, Any] | None = None,
    model: ModelKind | str = ModelKind.L1,
) -> Params:
    """Load, coerce and validate the simulation parameters.

    Args:
        path: YAML file; defaults to :data:`DEFAULT_PARAMS_PATH` (``02_params/rexome33.yaml``).
        level: Auger level ``"top"``, ``"middle"`` or ``"bottom"``; ``None`` uses
            ``superstructure.default_auger_level`` from the file (currently ``top``).
        overrides: Dotted path -> replacement value, applied in memory before coercion,
            for example ``{"actuator.oil_bulk_modulus_eff_Pa": 1.6e9}``. Derived values
            (such as ``contact.rigid_floor.L1.kn_per_pad_N_m``) are not recomputed.
        model: ``"L1"`` (default; fingerprint and fields as before S7) or ``"L2b_NSC"``
            (adds :attr:`Params.l2b`, the typed ``actuator.L2b_NSC``,
            ``contact.rigid_floor.L2b_NSC`` and ``simulation.L2b_NSC`` blocks, and ``model``
            to the fingerprint).

    Returns:
        Frozen :class:`Params`.

    Raises:
        ParamsError: Missing key, non-numeric value where a number belongs, wrong leg
            order, unknown level or model, an override of a key that does not exist, or
            (L2b_NSC) an axial operating point that the stiffness formula does not reproduce.
        OSError: The file cannot be read.
    """
    source_path = Path(path) if path is not None else DEFAULT_PARAMS_PATH
    file_bytes = source_path.read_bytes()
    loaded = yaml.safe_load(file_bytes.decode("utf-8"))
    if not isinstance(loaded, dict):
        raise ParamsError("<root>", f"{source_path} does not contain a YAML mapping")

    applied_overrides = copy.deepcopy(dict(overrides or {}))
    _apply_overrides(loaded, applied_overrides)
    coerced = _coerce_tree(loaded)

    root = _Reader(coerced, ())
    selected_level = _resolve_level(root, level)
    selected_model = _resolve_model(model)
    contact = _read_contact(root)
    l2b = (
        _read_l2b_nsc(root, contact.rigid_floor.L1.operating_extension_m,
                      rod_dead_length_override=ROD_DEAD_LENGTH_KEY in applied_overrides)
        if selected_model is ModelKind.L2B_NSC
        else None
    )
    return Params(
        source_path=source_path,
        level=selected_level,
        overrides=MappingProxyType(applied_overrides),
        meta=_read_meta(root),
        ground=_read_ground(root),
        superstructure=_read_superstructure(root, selected_level),
        actuator=_read_actuator(root),
        legs=_read_legs(root),
        contact=contact,
        control=Control(F_min_cylinder_N=root.child("control").number("F_min_cylinder_N")),
        simulation=_read_simulation(root),
        raw=_freeze(coerced),
        sha256=parameters_sha256(coerced, selected_level, selected_model),
        file_sha256=hashlib.sha256(file_bytes).hexdigest(),
        model=selected_model,
        l2b=l2b,
    )


def scm_run_sha256(params: Params) -> str:
    """Fingerprint of a soft-soil (SCM, S9) run: rigid-floor fingerprint + pad shapes + type.

    Decision D5 of the YAML bundle 2026-10-25: ``pad_shapes`` is left out of
    :attr:`Params.sha256` (:data:`SCM_ONLY_HASH_PATHS`), so an SCM run or snapshot must
    fingerprint it itself; a snapshot of the other pad type then never matches (5.30.5).
    Canonical form: ``{"params_sha256", "pad_shapes", "pad_type"}`` as UTF-8 JSON with sorted
    keys and no whitespace; ``pad_type`` is the selected type (``pad_shapes.default_type``
    after overrides, :attr:`Pad.pad_type`).

    Raises:
        ParamsError: The YAML has no ``pad_shapes`` block (a YAML from before the bundle).
    """
    if PAD_SHAPES_KEY not in params.raw:
        raise ParamsError(PAD_SHAPES_KEY, "missing; an SCM run needs the pad shape types")
    payload = {
        "params_sha256": params.sha256,
        "pad_shapes": _thaw(params.raw[PAD_SHAPES_KEY]),
        "pad_type": params.legs[0].pad.pad_type,
    }
    canonical = json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()
