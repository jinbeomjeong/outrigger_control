"""Load the shared simulation parameters (``02_params/rexome33.yaml``) into frozen dataclasses.

The YAML file is generated by ``04_scripts/00_cad/export_params.py`` and is never edited here.
The loader:

* coerces every value that must be a number to ``float`` (counts to ``int``). A string such
  as ``"1e9"`` - which PyYAML (YAML 1.1) returns as ``str`` because the exponent has no dot
  and no sign - becomes ``1e9``; a string that is not a number raises :class:`ParamsError`
  with the key path. Only keys listed in :data:`TEXT_KEYS` / :data:`TEXT_SUBTREES` may hold
  text, and only keys listed in :data:`FLAG_KEYS` may hold ``true`` / ``false``.
* fails on the first missing key with its dotted path.
* checks the leg order against :data:`LEG_ORDER` (FL, FR, RL, RR = indices 0-3).
* selects one auger level (``top``, ``middle``, ``bottom``).
* applies run-time overrides (dotted path -> value) in memory; the file is left untouched.
* fingerprints the loaded parameters with SHA-256 (see :func:`parameters_sha256`).

The blocks needed from S0 to S3 of ``00_docs/03_chrono/chrono_build_plan.md`` are typed;
everything else is reachable read-only through :attr:`Params.raw` and :meth:`Params.get`.

Units are SI. Angles are converted to radians in the typed fields (``*_rad``); the raw
mapping keeps the YAML values unchanged (for example ``swivel_tilt_range_deg``).
"""

