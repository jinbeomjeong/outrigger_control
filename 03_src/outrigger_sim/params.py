"""Relative tolerance of the k_ax(e_op) consistency check (YAML values have 9 digits)."""


def axial_stiffness_N_m(
    extension_m: float,
    *,
    bulk_modulus_Pa: float,
    head_area_m2: float,
    dead_length_m: float,
    k_rod_N_m: float,
    k_frame_N_m: float,
    k_concrete_N_m: float | None,
) -> float:
    """``k_ax(s) = 1 / (1/k_oil(s) + 1/k_rod + 1/k_frame [+ 1/k_concrete])`` [N/m],
    ``k_oil(s) = beta A_p / (L_0 + s)``; ``k_concrete_N_m=None`` drops the concrete (SCM).
    Engine independent (no pychrono)."""
    column = dead_length_m + extension_m
    if column <= 0.0:
        raise ValueError(f"oil column length {column} m <= 0 at extension {extension_m} m")
    flex = column / (bulk_modulus_Pa * head_area_m2) + 1.0 / k_rod_N_m + 1.0 / k_frame_N_m
    if k_concrete_N_m is not None:
        flex += 1.0 / k_concrete_N_m
    return 1.0 / flex


@dataclass(frozen=True, eq=False)
class Params:
    """Loaded, validated parameters. Compare two instances by :attr:`sha256`.

    Attribute paths mirror the YAML paths (``params.contact.rigid_floor.L1.kn_per_pad_N_m``)
    except :attr:`superstructure`, which holds only the selected auger level, and
    :attr:`legs`, which is a tuple in :data:`LEG_ORDER`.
    """

    source_path: Path
    level: AugerLevel
    overrides: Mapping[str, Any]
    meta: Meta
    ground: Ground
    superstructure: Superstructure
    actuator: Actuator
    legs: tuple[Leg, ...]
    contact: Contact
    control: Control
    simulation: Simulation
    raw: Mapping[str, Any]
    """Whole YAML after overrides and numeric coercion; read-only (lists become tuples)."""
    sha256: str
    """Fingerprint of the loaded parameters, see :func:`parameters_sha256`."""
    file_sha256: str
    """SHA-256 of the YAML file bytes as read (before overrides)."""
    model: ModelKind = ModelKind.L1
    """Model family selected at load time (``load_params(model=...)``)."""
    l2b: L2bNSC | None = None
    """Typed L2b-NSC blocks (``model="L2b_NSC"`` only; None for L1)."""

    def get(self, dotted_path: str) -> Any:
        """Return the raw value at ``dotted_path`` (for example ``"contact.crawler.friction"``).

        Raises:
            ParamsError: If the path does not exist.
        """
        node: Any = self.raw
        for depth, key in enumerate(dotted_path.split(".")):
            if not isinstance(node, Mapping) or key not in node:
                walked = ".".join(dotted_path.split(".")[: depth + 1])
                raise ParamsError(walked, "missing key")
            node = node[key]
        return node

    def leg(self, name: str) -> Leg:
        """Return the leg called ``name`` (one of :data:`LEG_ORDER`)."""
        if name not in LEG_ORDER:
            raise ParamsError(f"legs.{name}", f"unknown leg, expected one of {LEG_ORDER}")
        return self.legs[LEG_ORDER.index(name)]

    def numeric_string_paths(self) -> list[str]:
        """Paths of raw values that are strings but parse as numbers; empty after a load."""
        return find_numeric_strings(self.raw)


# --- path helpers ------------------------------------------------------------------------


def _format_path(path: KeyPath) -> str:
    text = ""
    for part in path:
        if isinstance(part, int):
            text += f"[{part}]"
        else:
            text += f".{part}" if text else part
    return text or "<root>"


def _leaf_key(path: KeyPath) -> str | None:
    """Nearest mapping key of a leaf (list indices are skipped)."""
    for part in reversed(path):
        if isinstance(part, str):
            return part
    return None


def _is_text_path(path: KeyPath) -> bool:
    keys_only = tuple(part for part in path if isinstance(part, str))
    for subtree in TEXT_SUBTREES:
        if keys_only[: len(subtree)] == subtree:
            return True
    return _leaf_key(path) in TEXT_KEYS


# --- numeric coercion --------------------------------------------------------------------


def _parse_float(value: Any, path: KeyPath) -> float:
    # bool is a subclass of int; a YAML true/false where a number belongs is an error.
    if isinstance(value, bool) or value is None:
        raise ParamsError(_format_path(path), f"expected a number, got {value!r}")
    if isinstance(value, int | float):
        number = float(value)
    elif isinstance(value, str):
        try:
            number = float(value)
        except ValueError:
            raise ParamsError(_format_path(path), f"not a number: {value!r}") from None
    else:
        raise ParamsError(_format_path(path), f"expected a number, got {type(value).__name__}")
    if not math.isfinite(number):
        raise ParamsError(_format_path(path), f"not a finite number: {value!r}")
    return number


def _parse_count(value: Any, path: KeyPath) -> int:
    if isinstance(value, bool) or not isinstance(value, int | str):
        raise ParamsError(_format_path(path), f"expected an integer count, got {value!r}")
    try:
        return int(value)
    except ValueError:
        raise ParamsError(_format_path(path), f"not an integer count: {value!r}") from None


def _coerce_leaf(value: Any, path: KeyPath) -> Any:
    if _is_text_path(path):
        if not isinstance(value, str):
            raise ParamsError(_format_path(path), f"expected text, got {value!r}")
        return value
    if _leaf_key(path) in COUNT_KEYS:
        return _parse_count(value, path)
    if _leaf_key(path) in FLAG_KEYS:
        return _parse_flag(value, path)
    return _parse_float(value, path)


def _parse_flag(value: Any, path: KeyPath) -> bool:
    if not isinstance(value, bool):
        raise ParamsError(_format_path(path), f"expected true or false, got {value!r}")
    return value


def _coerce_tree(node: Any, path: KeyPath = ()) -> Any:
    """Copy ``node`` with every number as float (counts as int) and text checked."""
    if isinstance(node, Mapping):
        coerced = {}
        for key, value in node.items():
            if not isinstance(key, str):
                raise ParamsError(_format_path(path), f"mapping key {key!r} is not a string")
            coerced[key] = _coerce_tree(value, (*path, key))
        return coerced
    if isinstance(node, list | tuple):
        return [_coerce_tree(item, (*path, index)) for index, item in enumerate(node)]
    return _coerce_leaf(node, path)


def find_numeric_strings(tree: Any, path: KeyPath = ()) -> list[str]:
    """Return the paths of string leaves in ``tree`` that parse as numbers.

    Independent of :data:`TEXT_KEYS`: it flags any string that ``float()`` accepts, so it
    can audit both the raw YAML and a loaded :attr:`Params.raw`.
    """
    if isinstance(tree, Mapping):
        found = []
        for key, value in tree.items():
            found.extend(find_numeric_strings(value, (*path, key)))
        return found
    if isinstance(tree, list | tuple):
        found = []
        for index, item in enumerate(tree):
            found.extend(find_numeric_strings(item, (*path, index)))
        return found
    if isinstance(tree, str):
        try:
            float(tree)
        except ValueError:
            return []
        return [_format_path(path)]
    return []


# --- overrides ---------------------------------------------------------------------------


def _apply_overrides(tree: dict[str, Any], overrides: Mapping[str, Any]) -> None:
    """Replace existing values in ``tree`` in place; unknown paths are an error."""
    for dotted_path, value in overrides.items():
        keys = dotted_path.split(".")
        parent: Any = tree
        for depth, key in enumerate(keys[:-1]):
            parent = parent.get(key) if isinstance(parent, dict) else None
            if not isinstance(parent, dict):
                walked = ".".join(keys[: depth + 1])
                raise ParamsError(walked, f"override {dotted_path!r}: no such mapping")
        if keys[-1] not in parent:
            raise ParamsError(dotted_path, "override of a key that does not exist")
        parent[keys[-1]] = copy.deepcopy(value)


# --- fingerprint -------------------------------------------------------------------------


def _without_excluded_paths(
    tree: dict[str, Any], extra: tuple[tuple[str, ...], ...] = ()
) -> dict[str, Any]:
    trimmed = copy.deepcopy(tree)
    for path in (*HASH_EXCLUDED_PATHS, *extra):
        parent: Any = trimmed
        for key in path[:-1]:
            parent = parent.get(key, {}) if isinstance(parent, dict) else {}
        if isinstance(parent, dict):
            parent.pop(path[-1], None)
    return trimmed


def parameters_sha256(
    coerced_tree: dict[str, Any], level: AugerLevel, model: ModelKind = ModelKind.L1
) -> str:
    """Fingerprint of loaded parameters, stable against key order and float spelling.

    Canonical form: ``{"level": <level>, "params": <tree>}`` as UTF-8 JSON with sorted keys,
    no whitespace and no NaN/inf. The tree must already be coerced, so ``1e9`` and
    ``1000000000.0`` are the same float and JSON writes Python's shortest round-trip repr.
    The level is included because the same file gives a different superstructure per level.
    Paths in :data:`HASH_EXCLUDED_PATHS` and :data:`SCM_ONLY_HASH_PATHS` are dropped (L1 also
    drops :data:`L2B_ONLY_HASH_PATHS`, S8). YAML comments never enter the hash.
    A model other than L1 adds ``"model": <model>`` to the payload (S7), so L1 fingerprints
    (and the saved L1 snapshots, R16) are unchanged and an L2b snapshot never matches L1.

    The tree is the file tree after overrides, as loaded: the pad polygons the loader copies
    into :class:`Pad` from ``pad_shapes`` are not written back into it, so the default pad type
    never enters a rigid-floor fingerprint.
    """
    excluded = SCM_ONLY_HASH_PATHS
    if model is ModelKind.L1:
        excluded = (*excluded, *L2B_ONLY_HASH_PATHS)
    payload: dict[str, Any] = {
        "level": level.value,
        "params": _without_excluded_paths(coerced_tree, excluded),
    }
    if model is not ModelKind.L1:
        payload["model"] = model.value
    canonical = json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _freeze(node: Any) -> Any:
    if isinstance(node, dict):
        return MappingProxyType({key: _freeze(value) for key, value in node.items()})
    if isinstance(node, list):
        return tuple(_freeze(item) for item in node)
    return node


def _thaw(node: Any) -> Any:
    """Inverse of :func:`_freeze` (plain dicts and lists, JSON-ready)."""
    if isinstance(node, Mapping):
        return {key: _thaw(value) for key, value in node.items()}
    if isinstance(node, tuple | list):
        return [_thaw(item) for item in node]
    return node


# --- typed readers -----------------------------------------------------------------------


def _check_numbers(value: Any, length: int, path: KeyPath) -> tuple[float, ...]:
    is_numeric_list = isinstance(value, list) and all(isinstance(item, float) for item in value)
    if not is_numeric_list or len(value) != length:
        raise ParamsError(_format_path(path), f"expected {length} numbers, got {value!r}")
    return tuple(value)


def _check_vector3(value: Any, path: KeyPath) -> Vector3:
    x, y, z = _check_numbers(value, 3, path)
    return (x, y, z)


@dataclass(frozen=True)
class _Reader:
    """Typed access to one coerced mapping; every error carries the full dotted path."""

    mapping: Mapping[str, Any]
    path: tuple[str, ...]

    def _value(self, key: str) -> Any:
        if key not in self.mapping:
            raise ParamsError(_format_path((*self.path, key)), "missing required key")
        return self.mapping[key]

    def _error(self, key: str, problem: str) -> ParamsError:
        return ParamsError(_format_path((*self.path, key)), problem)

    def child(self, key: str) -> _Reader:
        value = self._value(key)
        if not isinstance(value, Mapping):
            raise self._error(key, "expected a mapping")
        return _Reader(value, (*self.path, key))

    def number(self, key: str) -> float:
        value = self._value(key)
        if not isinstance(value, float):
            raise self._error(key, f"expected a number, got {value!r}")
        return value

    def text(self, key: str) -> str:
        value = self._value(key)
        if not isinstance(value, str):
            raise self._error(key, f"expected text, got {value!r}")
        return value

    def text_list(self, key: str) -> tuple[str, ...]:
        value = self._value(key)
        if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
            raise self._error(key, f"expected a list of text, got {value!r}")
        return tuple(value)

    def vector2(self, key: str) -> Vector2:
        first, second = _check_numbers(self._value(key), 2, (*self.path, key))
        return (first, second)

    def vector3(self, key: str) -> Vector3:
        return _check_vector3(self._value(key), (*self.path, key))

    def matrix3(self, key: str) -> Matrix3:
        rows = self._value(key)
        if not isinstance(rows, list) or len(rows) != 3:
            raise self._error(key, f"expected a 3x3 matrix, got {rows!r}")
        first, second, third = (
            _check_vector3(row, (*self.path, key, index)) for index, row in enumerate(rows)
        )
        return (first, second, third)

    def polygon(self, key: str) -> tuple[Vector2, ...]:
        vertices = self._value(key)
        if not isinstance(vertices, list) or len(vertices) < 3:
            raise self._error(key, "expected a polygon of at least 3 vertices")
        polygon = []
        for index, vertex in enumerate(vertices):
            x, y = _check_numbers(vertex, 2, (*self.path, key, index))
            polygon.append((x, y))
        return tuple(polygon)

    def per_leg(self, key: str) -> PerLeg:
        legs = self.child(key)
        if set(legs.mapping) != set(LEG_ORDER):
            raise self._error(key, f"expected legs {LEG_ORDER}, got {tuple(legs.mapping)}")
        fl, fr, rl, rr = (legs.number(name) for name in LEG_ORDER)
        return (fl, fr, rl, rr)


